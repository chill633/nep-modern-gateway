#!/usr/bin/env bash
# Stage 2: build Linux (6.12 LTS by default) with the M6G2C device tree.
#
# Sources: work/linux-$KERNEL_REF (one tree per version, so changing
#          KERNEL_REF never reuses an older tree)
# Outputs: work/kernel-install/{boot,lib/modules}
#
# Device-tree feature switches (see board-files/linux/imx6ul-zlg-m6g2c.dts
# for the full list and defaults), e.g.
#   M6G2C_ENABLE_CAN=1 M6G2C_ENABLE_FEC1=1 ./build.sh kernel

# shellcheck source=common.sh
source "$(dirname "$0")/common.sh"

need_cmds git make "${CROSS_COMPILE}gcc" bison flex bc lzop patch

SRC="$WORK/linux-$KERNEL_REF"
INSTALL="$WORK/kernel-install"
fetch_git "$KERNEL_GIT" "$KERNEL_REF" "$SRC"

# From Linux 6.5 the i.MX device trees live in arch/arm/boot/dts/nxp/imx/.
DTS_DIR="$SRC/arch/arm/boot/dts/nxp/imx"
[ -f "$DTS_DIR/imx6ul.dtsi" ] || DTS_DIR="$SRC/arch/arm/boot/dts"
[ -f "$DTS_DIR/imx6ul.dtsi" ] || die "imx6ul.dtsi not found in $SRC"

log "Adding the M6G2C device tree"
DTS="$DTS_DIR/${DTB_NAME}.dts"
cp "$TOP/board-files/linux/imx6ul-zlg-m6g2c.dts" "$DTS"
for opt in FEC1 FEC2 RTC LEDS UART78 UART2345 SPI MI200E ADC GPIO_HOG DISPLAY TOUCH BEEPER NAND CAN USB; do
	var="M6G2C_ENABLE_${opt}"
	if [ -n "${!var:-}" ]; then
		sed -i "s/^#define ${var}\t.*/#define ${var}\t${!var}/" "$DTS"
		log "DT option ${var}=${!var}"
	fi
done

# External hardware watchdog: prepend the M6G2C_WDT_* macros to the DTS.
parse_wdt_gpio
if [ -n "$WDT_BANK" ]; then
	pad=$(find_gpio_pad "$DTS_DIR/imx6ul-pinfunc.h" MX6UL_PAD_)
	{
		echo "/* generated by scripts/02-kernel.sh from WDT_GPIO=$WDT_GPIO */"
		echo "#define M6G2C_WDT_PAD		$pad"
		echo "#define M6G2C_WDT_GPIO_REF	&gpio${WDT_BANK}"
		echo "#define M6G2C_WDT_PIN		$WDT_PIN"
		echo "#define M6G2C_WDT_MARGIN_MS	$WDT_MARGIN_MS"
		cat "$DTS"
	} > "$DTS.new" && mv "$DTS.new" "$DTS"
	log "Watchdog feed on GPIO${WDT_BANK}_IO$(printf %02d "$WDT_PIN") ($pad)"
else
	warn "WDT_GPIO not set: Linux will not feed the module's external watchdog"
fi

grep -q "${DTB_NAME}.dtb" "$DTS_DIR/Makefile" ||
	printf '\ndtb-$(CONFIG_SOC_IMX6UL) += %s.dtb\n' "$DTB_NAME" >> "$DTS_DIR/Makefile"

# Kernel patches (patches/linux/*.patch), applied once per tree.
for p in "$TOP"/patches/linux/*.patch; do
	[ -e "$p" ] || continue
	if patch -d "$SRC" -p1 -R --dry-run -s -f < "$p" >/dev/null 2>&1; then
		log "Patch already applied: $(basename "$p")"
	elif patch -d "$SRC" -p1 --dry-run -s -f < "$p" >/dev/null 2>&1; then
		patch -d "$SRC" -p1 -s -f < "$p"
		log "Applied $(basename "$p")"
	else
		die "patch $(basename "$p") does not apply to $KERNEL_REF"
	fi
done

# Extra drivers (board-files/linux/drivers), added to drivers/misc.
#   nep-mi200e.c -> plc_mi200e_o.ko: NEP's MI200E power-line modems, under
#   the module name gateway-plc's scripts expect.
MISC="$SRC/drivers/misc"
cp "$TOP/board-files/linux/drivers/nep-mi200e.c" "$MISC/"
grep -q 'config NEP_MI200E' "$MISC/Kconfig" || {
	cp "$MISC/Kconfig" "$MISC/Kconfig.orig"
	# insert before the closing "endmenu"
	awk '
		/^endmenu/ && !done {
			print "config NEP_MI200E"
			print "\ttristate \"NEP MI200E power-line modems (ZLG EPC-M6G2C)\""
			print "\tdepends on OF && GPIOLIB && (ARCH_MXC || COMPILE_TEST)"
			print "\thelp"
			print "\t  The three MI200E PLC modems of the EPC-M6G2C gateway, on ECSPI1"
			print "\t  and EPIT2, as /dev/mi200e for NEP'"'"'s gateway-plc. The module is"
			print "\t  called plc_mi200e_o."
			print ""
			done = 1
		}
		{ print }
	' "$MISC/Kconfig.orig" > "$MISC/Kconfig"
}
grep -q 'CONFIG_NEP_MI200E' "$MISC/Makefile" ||
	printf '\nobj-$(CONFIG_NEP_MI200E)\t+= plc_mi200e_o.o\nplc_mi200e_o-y\t\t:= nep-mi200e.o\n' >> "$MISC/Makefile"

# Start gpio-wdt as soon as the GPIO controllers exist.
#
# With GPIO_WATCHDOG_ARCH_INITCALL the driver registers at arch_initcall, but
# gpio-mxc only at subsys_initcall. Its first probe therefore defers, and
# deferred probes are not retried until late_initcall, after every other
# built-in driver. That is far beyond the ~1.1-1.6 s the external watchdog
# allows. subsys_initcall_sync runs right after the GPIO controllers bind.
WDT_SRC="$SRC/drivers/watchdog/gpio_wdt.c"
if grep -q '^arch_initcall(gpio_wdt_init);' "$WDT_SRC"; then
	sed -i 's/^arch_initcall(gpio_wdt_init);/subsys_initcall_sync(gpio_wdt_init); \/* m6g2c *\//' "$WDT_SRC"
	log "Patched gpio_wdt to subsys_initcall_sync"
elif ! grep -q '^subsys_initcall_sync(gpio_wdt_init);' "$WDT_SRC"; then
	die "could not patch $WDT_SRC (KERNEL_REF=$KERNEL_REF changed it?)"
fi

export ARCH=arm CROSS_COMPILE

log "Configuring (imx_v6_v7_defconfig + board-files/linux/m6g2c.config)"
# Merge into the *minimal* defconfig, not into the full .config that
# "make imx_v6_v7_defconfig" writes. In the full file, options that were only
# selected by something else (DEBUG_LOCK_ALLOC by PROVE_LOCKING, I2C by DRM,
# ...) appear as explicit settings. Switching the selector off then leaves them
# on: that's how lockdep survived "# CONFIG_PROVE_LOCKING is not set".
FRAG="$TOP/board-files/linux/m6g2c.config"
"$SRC/scripts/kconfig/merge_config.sh" -m -O "$SRC" \
	"$SRC/arch/arm/configs/imx_v6_v7_defconfig" "$FRAG"
make -C "$SRC" olddefconfig

# Every fragment line must have taken effect; stop if any didn't.
bad=""
while IFS= read -r line; do
	case "$line" in
	CONFIG_*=*)
		grep -qxF -- "$line" "$SRC/.config" || bad+="  wanted $line, got: $(grep -E "^(# )?${line%%=*}[= ]" "$SRC/.config" || echo unset)"$'\n' ;;
	"# CONFIG_"*" is not set")
		sym=${line#\# }; sym=${sym%% *}
		! grep -qE "^${sym}=" "$SRC/.config" || bad+="  wanted $line, got: $(grep -E "^${sym}=" "$SRC/.config")"$'\n' ;;
	esac
done < "$FRAG"
[ -z "$bad" ] || die "kernel config fragment not fully applied:"$'\n'"$bad"
log "All $(grep -cE '^(CONFIG_|# CONFIG_.* is not set)' "$FRAG") fragment settings applied"

log "Building zImage, dtbs and modules"
make -C "$SRC" LOCALVERSION=-m6g2c -j"$JOBS" zImage dtbs modules

KVER=$(make -s -C "$SRC" LOCALVERSION=-m6g2c kernelrelease)
log "Kernel release: $KVER"

rm -rf "$INSTALL"
mkdir -p "$INSTALL/boot/dtbs"
make -C "$SRC" LOCALVERSION=-m6g2c INSTALL_MOD_PATH="$INSTALL" \
	INSTALL_MOD_STRIP=1 modules_install
rm -f "$INSTALL/lib/modules/$KVER/build" "$INSTALL/lib/modules/$KVER/source"

cp "$SRC/arch/arm/boot/zImage"                        "$INSTALL/boot/zImage"
cp "$DTS_DIR/${DTB_NAME}.dtb"                         "$INSTALL/boot/dtbs/"
cp "$SRC/System.map"                                  "$INSTALL/boot/System.map-$KVER"
cp "$SRC/.config"                                     "$INSTALL/boot/config-$KVER"
echo "$KVER" > "$INSTALL/boot/kernel-release"

fix_owner "$INSTALL"
log "Kernel done: $INSTALL"
